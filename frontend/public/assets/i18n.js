  function locale(explicit) {
    const direct = String(explicit || "").slice(0, 2).toLowerCase();
    if (SUPPORTED.includes(direct)) return direct;
    let requested = "";
    try { requested = new URLSearchParams(global.location.search).get("lang") || ""; } catch (_) {}
    requested = requested.slice(0, 2).toLowerCase();
    if (SUPPORTED.includes(requested)) return requested;
    const browser = String(global.navigator?.language || "en").slice(0, 2).toLowerCase();
    return SUPPORTED.includes(browser) ? browser : "en";
  }

  function t(key, vars, explicit) {
    const lang = locale(explicit);
    const template = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_m, name) => {
      const value = vars && Object.prototype.hasOwnProperty.call(vars, name) ? vars[name] : "";
      return String(value);
    });
  }

  function applyStatic(root) {
    const scope = root || document;
    const lang = locale();
    document.documentElement.lang = lang;
    document.title = t("document.title", null, lang);
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", t("document.description", null, lang));
    scope.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n, null, lang);
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.title = t(node.dataset.i18nTitle, null, lang);
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAria, null, lang));
    });
  }

  function mapLibreLocale(explicit) {
    return { ...MAPLIBRE.en, ...(MAPLIBRE[locale(explicit)] || {}) };
  }

  global.AtlasI18n = { SUPPORTED, MESSAGES, locale, t, applyStatic, mapLibreLocale };
